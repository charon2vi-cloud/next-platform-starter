export function isSupported(code) {
    return Object.prototype.hasOwnProperty.call(dictionaries, code);
}

export function getDictionary(code) {
    return dictionaries[isSupported(code) ? code : DEFAULT_LANGUAGE];
}

/** Pick the best language from a browser or Accept-Language string. */
export function resolveLanguage(input) {
    if (!input) return DEFAULT_LANGUAGE;
    const candidates = String(input)
        .split(',')
        .map((part) => part.split(';')[0].trim().slice(0, 2).toLowerCase());
    return candidates.find(isSupported) || DEFAULT_LANGUAGE;
}

/** Interpolate {placeholders}. */
export function t(dictionary, key, values = {}) {
    const template = dictionary[key];
    if (typeof template !== 'string') return template ?? '';
    return template.replace(/\{(\w+)\}/g, (match, name) => (name in values ? values[name] : match));
}
